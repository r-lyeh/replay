-- hurdy (https://codeberg.org/apicici/hurdy): a brace-style language that
-- compiles to Lua. Used for code leaves (name.hurdy) in Replay worlds.
local syntax = require "core.syntax"

syntax.add {
  files = "%.hurdy$",
  comment = "--",
  patterns = {
    { pattern = { '"', '"', '\\' },       type = "string"   },
    { pattern = { "'", "'", '\\' },       type = "string"   },
    { pattern = { "%[%[", "%]%]" },       type = "string"   },
    { pattern = { "%-%*", "%*%-" },       type = "comment"  },
    { pattern = "%-%-.-\n",               type = "comment"  },
    { pattern = "-?0x%x+",                type = "number"   },
    { pattern = "-?%d+[%d%.eE]*",         type = "number"   },
    { pattern = "-?%.?%d+",               type = "number"   },
    { pattern = "%.%.%.?=?",              type = "operator" },
    { pattern = "[<>!=%+%-%*/%%&|]=",     type = "operator" },
    { pattern = "%*%*",                   type = "operator" },
    { pattern = "[%+%-=/%*%^%%#<>!&|~?@]", type = "operator" },
    { pattern = "[%a_][%w_]*%s*%f[(\"{]", type = "function" },
    { pattern = "[%a_][%w_]*",            type = "symbol"   },
  },
  symbols = {
    ["var"]      = "keyword",
    ["global"]   = "keyword",
    ["function"] = "keyword",
    ["method"]   = "keyword",
    ["if"]       = "keyword",
    ["else"]     = "keyword",
    ["elseif"]   = "keyword",
    ["for"]      = "keyword",
    ["in"]       = "keyword",
    ["while"]    = "keyword",
    ["repeat"]   = "keyword",
    ["until"]    = "keyword",
    ["break"]    = "keyword",
    ["continue"] = "keyword",
    ["return"]   = "keyword",
    ["and"]      = "keyword",
    ["or"]       = "keyword",
    ["import"]   = "keyword",
    ["from"]     = "keyword",
    ["as"]       = "keyword",
    ["self"]     = "keyword2",
    ["true"]     = "literal",
    ["false"]    = "literal",
    ["nil"]      = "literal",
  },
}
