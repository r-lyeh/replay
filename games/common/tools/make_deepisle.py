img = Image.new('RGBA', (128, 48), (0, 0, 0, 0))
for i, name in enumerate(ORDER):
    rows = [r for r in S[name].strip('\n').split('\n')]
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), (name, [len(r) for r in rows])
    for y, r in enumerate(rows):
        for x, ch in enumerate(r):
            if ch != '.': img.putpixel(((i % 8) * 16 + x, (i // 8) * 16 + y), PAL[ch] + (255,))
img.save(os.path.join(HERE, '..', 'deepisle.png'))
print('\n'.join('%2d %s' % (i, n) for i, n in enumerate(ORDER)))
